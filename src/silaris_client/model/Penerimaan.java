package silaris_client.model;

public class Penerimaan {
    
    public String idPen;
    public String tanggalPen;
    public Integer totalLin;
    public String petugasPen;
    public String ketPen;

    public String getIdPen() {
        return idPen;
    }

    public void setIdPen(String idPen) {
        this.idPen = idPen;
    }

    public String getTanggalPen() {
        return tanggalPen;
    }

    public void setTanggalPen(String tanggalPen) {
        this.tanggalPen = tanggalPen;
    }

    public Integer getTotalLin() {
        return totalLin;
    }

    public void setTotalLin(Integer totalLin) {
        this.totalLin = totalLin;
    }

    public String getPetugasPen() {
        return petugasPen;
    }

    public void setPetugasPen(String petugasPen) {
        this.petugasPen = petugasPen;
    }

    public String getKetPen() {
        return ketPen;
    }

    public void setKetPen(String ketPen) {
        this.ketPen = ketPen;
    }
    
    
}

